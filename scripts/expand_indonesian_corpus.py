def expand_corpus():
    corpus_csv = "data/corpus/indonesian_smart_home_corpus_31_intents.csv"
    df_old = pd.read_csv(corpus_csv)
    print(f"Total frasa awal di korpus: {len(df_old)} baris (15 frasa / intent)")
    
    new_rows = []
    # Salin data lama
    for idx, r in df_old.iterrows():
        new_rows.append(r.to_dict())
        
    # Tambahkan frasa casual sehari-hari (20 frasa baru per intent -> total 35 frasa / intent)
    added_count = 0
    for intent_id, phrases in CASUAL_EXTENSIONS.items():
        # Cari baris contoh untuk intent_id tersebut
        sample_row = df_old[df_old["intent_id"] == intent_id].iloc[0]
        action = sample_row["action"]
        obj = sample_row["object"]
        loc = sample_row["location"]
        en_sample = sample_row["english_sample"]
        
        for p in phrases:
            new_rows.append({
                "intent_id": intent_id,
                "action": action,
                "object": obj,
                "location": loc,
                "english_sample": en_sample,
                "indonesian_phrase": p,
            })
            added_count += 1
            
    df_new = pd.DataFrame(new_rows)
    df_new.to_csv(corpus_csv, index=False)
    
    # Also save markdown documentation
    md_path = "docs/corpus_indonesia_31_intents.md"
    with open(md_path, "w", encoding="utf-8") as f:
        f.write("# Korpus Perintah Suara Smart Home Bahasa Indonesia (SVARA)\n\n")
        f.write(f"Total Intents: 31 | Frasa per Intent: 35 | **Total Frasa: {len(df_new)} frasa**\n\n")
        f.write("Mencakup variasi formal, semi-formal, dan **slang/sehari-hari super luwes** (nyalain, matiin, idupin, gedein, kecilin, WC, toilet, dll).\n\n")
        
        for intent_id, group in df_new.groupby("intent_id"):
            first = group.iloc[0]
            f.write(f"## Intent {intent_id}: `{first['action']}` + `{first['object']}` + `{first['location']}`\n")
            f.write(f"- Contoh Bahasa Inggris: *{first['english_sample']}*\n")
            f.write("- Variasi Bahasa Indonesia:\n")
            for _, r in group.iterrows():
                f.write(f"  - {r['indonesian_phrase']}\n")
            f.write("\n")
            
    print("\n" + "="*50)
    print("KORPUS BAHASA INDONESIA BERHASIL DIEKSPANSI BESAR-BESARAN!")
    print(f"- Frasa baru ditambahkan : {added_count} frasa santai sehari-hari")
    print(f"- Total frasa sekarang   : {len(df_new)} frasa (35 frasa / intent)")
    print(f"- Disimpan di            : {corpus_csv}")
    print(f"- Dokumentasi Markdown   : {md_path}")
    print("="*50)

if __name__ == "__main__":
    expand_corpus()
